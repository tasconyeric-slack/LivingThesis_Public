export const LANGUAGE_STORAGE = "living-thesis-ui-language";
export function chooseLanguage(saved, browserLanguage = "en") {
  return ["en", "zh"].includes(saved)
    ? saved
    : /^zh(?:-|$)/i.test(browserLanguage)
      ? "zh"
      : "en";
}
export function translate(language, key, params = {}) {
  const text = messages[language]?.[key] ?? messages.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) =>
    String(params[name] ?? `{${name}}`),
  );
}
